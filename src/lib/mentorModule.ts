/** 답안 채점: 전부 맞혀야 통과. 틀린 문항 번호(0부터)를 돌려준다. */
export function gradeQuiz(unit: ModuleUnit, answers: (number | null)[]): { passed: boolean; wrong: number[] } {
  const wrong = unit.quiz.map((q, i) => (answers[i] === q.answer ? -1 : i)).filter((i) => i >= 0);
  return { passed: wrong.length === 0, wrong };
}
